'use client';

import React, { useState } from 'react';
import { ArrowRight, ShieldCheck, AlertTriangle, Building2, Check, RefreshCw, CheckCircle2, Split, Clock, TrendingUp } from 'lucide-react';
import { Organization } from '@/types';

interface AutoReplenishDeckProps {
  currentOrg: Organization | null;
  onPunchOrder: (items: any[]) => void;
}

interface ReplenishItem {
  id: string;
  brand_name: string;
  pack_size: string;
  master_product_id: string;
  schedule: string;
  current_stock: number;
  min_threshold: number;
  target_stock: number;
  suggested_qty: number;
  avg_daily_sales: number;
  data_source: 'Based on 7-Day Velocity' | 'Verified POS Sync';
  urgency: 'CRITICAL' | 'NORMAL';
  primary_distributor: {
    id: string;
    name: string;
    batch_id: string;
    ptr: number;
    gst_pct: number;
    scheme?: string;
    available: number;
  };
  shortfall: {
    available_at_primary: number;
    shortfall_qty: number;
    alt_distributor_id: string;
    alt_distributor_name: string;
    alt_ptr: number;
  } | null;
  split_accepted?: boolean;
  spike_analysis?: {
    isSpikeDetected: boolean;
    confidencePct: number;
    anomalyType: string;
    baselineDailySales: number;
    spikeDailySales: number;
    spikeFactor: number;
    rawSuggestedQty: number;
    dampenedSuggestedQty: number;
    excessOrderRiskQty: number;
    capitalAtRisk: number;
    cautionMessage: string;
    recommendedAction: string;
  };
  spike_excluded?: boolean;
}

export function AutoReplenishDeck({ currentOrg, onPunchOrder }: AutoReplenishDeckProps) {
  const [groupBy, setGroupBy] = useState<'distributor' | 'urgency'>('urgency');
  const [successOrder, setSuccessOrder] = useState<string | null>(null);
  const [punching, setPunching] = useState(false);
  const [activeFlashId, setActiveFlashId] = useState<string | null>(null);

  // Suggested replenishment draft items generated by engine formula
  const [draftItems, setDraftItems] = useState<ReplenishItem[]>([
    {
      id: 'item-1',
      brand_name: 'Dolo 650 Tablet',
      pack_size: '15 Tablets / Strip',
      master_product_id: 'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa',
      schedule: 'SCHEDULE_H',
      current_stock: 12,
      min_threshold: 20,
      target_stock: 60,
      suggested_qty: 48,
      avg_daily_sales: 8.5,
      data_source: 'Based on 7-Day Velocity',
      urgency: 'CRITICAL',
      primary_distributor: {
        id: '11111111-1111-1111-1111-111111111111',
        name: 'MedLife Wholesale Pharma',
        batch_id: '11110001-0000-0000-0000-000000000001',
        ptr: 24.39,
        gst_pct: 12,
        scheme: 'Buy 10 Get 1 Free',
        available: 240,
      },
      shortfall: null,
      spike_analysis: {
        isSpikeDetected: true,
        confidencePct: 94,
        anomalyType: 'CHRONIC_PATIENT_BULK_PURCHASE',
        baselineDailySales: 2.1,
        spikeDailySales: 8.5,
        spikeFactor: 4.1,
        rawSuggestedQty: 48,
        dampenedSuggestedQty: 15,
        excessOrderRiskQty: 33,
        capitalAtRisk: 901,
        cautionMessage: '⚠️ Caution: One-Time Outlier Surge Detected. A single customer bought 45 units on Oct 20 (likely 3-4 months chronic supply). Store normal velocity is only ~2.1 units/day.',
        recommendedAction: 'Dumb ERPs order 48 units. M37 recommends dampening order to 15 units to prevent ₹901 in dead stock.',
      },
      spike_excluded: false,
    },
    {
      id: 'item-2',
      brand_name: 'Azithral 500 Tablet',
      pack_size: '5 Tablets / Strip',
      master_product_id: 'cccccccc-cccc-cccc-cccc-cccccccccccc',
      schedule: 'SCHEDULE_H1',
      current_stock: 4,
      min_threshold: 10,
      target_stock: 100,
      suggested_qty: 100,
      avg_daily_sales: 4.8,
      data_source: 'Based on 7-Day Velocity',
      urgency: 'CRITICAL',
      primary_distributor: {
        id: '11111111-1111-1111-1111-111111111111',
        name: 'Sri Balaji Pharma',
        batch_id: '11110002-0000-0000-0000-000000000002',
        ptr: 89.25,
        gst_pct: 12,
        scheme: 'Buy 20 Get 2 Free',
        available: 40,
      },
      shortfall: {
        available_at_primary: 40,
        shortfall_qty: 60,
        alt_distributor_id: '22222222-2222-2222-2222-222222222222',
        alt_distributor_name: 'Sai Medicals',
        alt_ptr: 89.50,
      },
    },
    {
      id: 'item-3',
      brand_name: 'CareProtect Nitrile Gloves (M)',
      pack_size: 'Box of 100 Pieces',
      master_product_id: 'dddddddd-dddd-dddd-dddd-dddddddddddd',
      schedule: 'NON_PHARMA',
      current_stock: 6,
      min_threshold: 8,
      target_stock: 25,
      suggested_qty: 19,
      avg_daily_sales: 2.1,
      data_source: 'Verified POS Sync',
      urgency: 'NORMAL',
      primary_distributor: {
        id: '22222222-2222-2222-2222-222222222222',
        name: 'Apex Stockists',
        batch_id: '22220002-0000-0000-0000-000000000002',
        ptr: 420.00,
        gst_pct: 12,
        scheme: '5% off on 10+ boxes',
        available: 95,
      },
      shortfall: null,
    },
  ]);

  // Fetch dynamic suggestions from backend for current retailer
  React.useEffect(() => {
    if (!currentOrg?.id) return;
    fetch(`/api/replenishment/suggestions?retailer_id=${currentOrg.id}`)
      .then((res) => res.json())
      .then((data) => {
        if (data.success && data.suggestions && data.suggestions.length > 0) {
          setDraftItems(data.suggestions);
        }
      })
      .catch(console.error);
  }, [currentOrg]);

  const triggerTactile = (id: string) => {
    setActiveFlashId(id);
    setTimeout(() => setActiveFlashId(null), 300);
  };

  const updateItemQty = (id: string, delta: number) => {
    triggerTactile(id);
    setDraftItems((items) =>
      items.map((it) => {
        if (it.id === id) {
          const newQty = Math.max(1, it.suggested_qty + delta);
          return { ...it, suggested_qty: newQty };
        }
        return it;
      })
    );
  };

  const handleAcceptSplit = (itemId: string) => {
    triggerTactile(itemId);
    setDraftItems((items) =>
      items.map((it) => {
        if (it.id === itemId) {
          return { ...it, split_accepted: true };
        }
        return it;
      })
    );
  };

  const toggleExcludeSpike = (itemId: string) => {
    triggerTactile(itemId);
    setDraftItems((items) =>
      items.map((it) => {
        if (it.id === itemId && it.spike_analysis) {
          const isExcluding = !it.spike_excluded;
          return {
            ...it,
            spike_excluded: isExcluding,
            suggested_qty: isExcluding
              ? it.spike_analysis.dampenedSuggestedQty
              : it.spike_analysis.rawSuggestedQty,
          };
        }
        return it;
      })
    );
  };

  const totalReplenishmentValue = draftItems.reduce((acc, it) => {
    return acc + it.suggested_qty * it.primary_distributor.ptr * (1 + it.primary_distributor.gst_pct / 100);
  }, 0);

  const totalUnits = draftItems.reduce((acc, it) => acc + it.suggested_qty, 0);

  const handlePunchDraft = async () => {
    setPunching(true);
    try {
      const primaryItems = draftItems.map((it) => ({
        master_product_id: it.master_product_id,
        brand_name: it.brand_name,
        batch_id: it.primary_distributor.batch_id,
        unit_ptr: it.primary_distributor.ptr,
        gst_pct: it.primary_distributor.gst_pct,
        quantity: it.split_accepted && it.shortfall ? it.shortfall.available_at_primary : it.suggested_qty,
        schedule: it.schedule,
      }));

      const res = await fetch('/api/orders/checkout', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          retailer_id: currentOrg?.id,
          distributor_id: draftItems[0].primary_distributor.id,
          items: primaryItems,
          generation_mode: 'AUTO_ALLOCATED',
        }),
      });

      const data = await res.json();
      if (!res.ok || !data.success) throw new Error(data.error || 'Failed to punch draft');

      setSuccessOrder(data.order_number);
      onPunchOrder(draftItems);
    } catch (err: any) {
      alert(`Error punching auto-order: ${err.message}`);
    } finally {
      setPunching(false);
    }
  };

  const renderItemCard = (item: ReplenishItem) => {
    const fillPct = Math.min(100, Math.round(((item.current_stock + item.suggested_qty) / item.target_stock) * 100));
    const isFlashing = activeFlashId === item.id;

    return (
      <div
        key={item.id}
        className={`rounded-xl border p-4 sm:p-5 transition-all shadow-xs ${
          isFlashing
            ? 'ring-2 ring-teal-500 border-teal-500 bg-teal-50/20'
            : 'bg-white dark:bg-[#0A0A0A] border-slate-200 dark:border-neutral-800 hover:border-slate-300 dark:hover:border-neutral-700'
        }`}
      >
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
          {/* Product & Micro-indicators */}
          <div className="flex-1">
            <div className="flex items-center space-x-2 flex-wrap gap-y-1">
              <span className="font-mono text-[11px] font-bold text-slate-700 dark:text-neutral-300 uppercase bg-slate-100 dark:bg-[#171717] px-2 py-0.5 rounded border border-slate-200 dark:border-neutral-700">
                {item.pack_size}
              </span>
              <span
                className={`px-2 py-0.5 rounded text-[10px] font-mono font-bold ${
                  item.urgency === 'CRITICAL'
                    ? 'bg-rose-50 text-rose-800 border border-rose-200 dark:bg-rose-950/50 dark:text-rose-300 dark:border-rose-800'
                    : 'bg-emerald-50 text-emerald-800 border border-emerald-200 dark:bg-emerald-950/50 dark:text-emerald-300 dark:border-emerald-800'
                }`}
              >
                {item.urgency === 'CRITICAL' ? '● CRITICAL (< Min Threshold)' : '● ROUTINE REORDER'}
              </span>
              <span className="px-2 py-0.5 rounded text-[10px] font-mono bg-slate-100 dark:bg-slate-800 text-slate-600 dark:text-slate-300 border border-slate-200 dark:border-slate-700">
                {item.data_source}
              </span>
            </div>

            <h3 className="text-base font-bold text-slate-900 dark:text-white mt-1.5">{item.brand_name}</h3>

            <div className="mt-1 flex items-center space-x-3 text-xs text-slate-500 dark:text-slate-400 flex-wrap gap-y-1">
              <span className="flex items-center space-x-1">
                <Building2 className="w-3.5 h-3.5 text-teal-600 dark:text-teal-400" />
                <span>
                  Allocated to: <strong className="text-slate-800 dark:text-slate-200">{item.primary_distributor.name}</strong>
                </span>
              </span>
              <span>•</span>
              <span className="font-mono">
                PTR: ₹{item.primary_distributor.ptr.toFixed(2)}
              </span>
              {item.primary_distributor.scheme && (
                <span className="rounded bg-teal-50 dark:bg-teal-950/40 px-1.5 py-0.5 text-[10px] font-bold text-teal-800 dark:text-teal-300 border border-teal-200 dark:border-teal-800 font-mono">
                  {item.primary_distributor.scheme}
                </span>
              )}
            </div>

            {/* Target Stock Visual Progress Bar */}
            <div className="mt-3.5 max-w-md">
              <div className="flex justify-between text-[11px] font-mono text-slate-600 dark:text-slate-400 mb-1">
                <span>
                  Shelf: <strong className="text-slate-900 dark:text-white">{item.current_stock}</strong> → Suggested:{' '}
                  <strong className="text-teal-700 dark:text-teal-400">+{item.suggested_qty}</strong>
                </span>
                <span>Target: {item.target_stock} units ({fillPct}%)</span>
              </div>
              <div className="h-1.5 w-full bg-slate-100 dark:bg-slate-800 rounded-full overflow-hidden border border-slate-200 dark:border-slate-700">
                <div
                  className="h-full bg-teal-600 dark:bg-teal-400 rounded-full transition-all duration-300"
                  style={{ width: `${fillPct}%` }}
                />
              </div>
            </div>
          </div>

          {/* Inline Stepper & Line Total */}
          <div className="flex flex-col sm:flex-row items-start sm:items-center gap-4 self-end md:self-auto">
            <div className="flex items-center bg-slate-100 dark:bg-slate-900 border border-slate-300 dark:border-slate-700 rounded-lg overflow-hidden text-xs">
              <button
                onClick={() => updateItemQty(item.id, -1)}
                className="px-3 py-2 text-slate-500 hover:text-slate-900 dark:hover:text-white hover:bg-slate-200 dark:hover:bg-slate-800 font-mono font-bold cursor-pointer transition-colors"
              >
                -
              </button>
              <span className="px-3 font-mono font-bold text-slate-900 dark:text-white text-sm tabular-nums">
                {item.suggested_qty}
              </span>
              <button
                onClick={() => updateItemQty(item.id, 1)}
                className="px-3 py-2 text-slate-500 hover:text-slate-900 dark:hover:text-white hover:bg-slate-200 dark:hover:bg-slate-800 font-mono font-bold cursor-pointer transition-colors"
              >
                +
              </button>
            </div>

            <div className="text-right font-mono min-w-[130px]">
              <div className="text-[10px] text-slate-500 uppercase tracking-wider font-semibold">Line Total (Incl. GST)</div>
              <div className="text-base font-black text-slate-900 dark:text-white tabular-nums">
                ₹{(item.suggested_qty * item.primary_distributor.ptr * (1 + item.primary_distributor.gst_pct / 100)).toFixed(2)}
              </div>
            </div>
          </div>
        </div>

        {/* The One-Tap Shortfall Resolver */}
        {item.shortfall && !item.split_accepted && (
          <div className="mt-4 pt-3 border-t border-slate-100 dark:border-slate-800">
            <div className="bg-amber-50 dark:bg-amber-950/40 rounded-xl p-3 border border-amber-200 dark:border-amber-800/80 flex flex-col sm:flex-row sm:items-center justify-between gap-3 text-xs">
              <div className="flex items-start space-x-2">
                <AlertTriangle className="w-4 h-4 text-amber-600 dark:text-amber-400 shrink-0 mt-0.5" />
                <div>
                  <strong className="text-amber-900 dark:text-amber-200 font-semibold">Shortfall Detected:</strong>{' '}
                  <span className="font-mono">{item.shortfall.available_at_primary}/{item.suggested_qty}</span> available at{' '}
                  <strong className="text-slate-900 dark:text-white">{item.primary_distributor.name}</strong> → Re-route{' '}
                  <span className="font-mono text-amber-800 dark:text-amber-300 font-bold">{item.shortfall.shortfall_qty}</span> to{' '}
                  <strong className="text-slate-900 dark:text-white">{item.shortfall.alt_distributor_name}</strong>?
                </div>
              </div>

              <button
                onClick={() => handleAcceptSplit(item.id)}
                className="inline-flex items-center space-x-1.5 px-3 py-1.5 rounded-lg bg-amber-500 hover:bg-amber-600 text-slate-950 font-bold text-xs shrink-0 transition-all shadow-xs active:scale-95 cursor-pointer"
              >
                <Split className="w-3.5 h-3.5" />
                <span>Accept Split</span>
              </button>
            </div>
          </div>
        )}

        {/* Split Resolved State */}
        {item.shortfall && item.split_accepted && (
          <div className="mt-4 pt-3 border-t border-slate-100 dark:border-slate-800">
            <div className="bg-emerald-50 dark:bg-emerald-950/40 rounded-xl p-3 border border-emerald-200 dark:border-emerald-800 flex items-center justify-between text-xs text-emerald-800 dark:text-emerald-300 font-mono">
              <div className="flex items-center space-x-2">
                <Check className="w-4 h-4 text-emerald-600 dark:text-emerald-400 shrink-0 stroke-[3]" />
                <span>
                  Split Confirmed: <strong>{item.shortfall.available_at_primary} units</strong> → {item.primary_distributor.name} | <strong>{item.shortfall.shortfall_qty} units</strong> → {item.shortfall.alt_distributor_name}
                </span>
              </div>
              <span className="text-[10px] text-emerald-700 dark:text-emerald-300 font-bold uppercase bg-emerald-100 dark:bg-emerald-900/60 px-2 py-0.5 rounded">
                Optimized
              </span>
            </div>
          </div>
        )}

        {/* Anomaly & One-Time Spike Caution Alert (Chronic Patient 3-4 months purchase) */}
        {item.spike_analysis && item.spike_analysis.isSpikeDetected && (
          <div className="mt-4 pt-3 border-t border-slate-100 dark:border-slate-800">
            <div
              className={`rounded-xl p-3.5 border transition-all ${
                item.spike_excluded
                  ? 'bg-emerald-50 dark:bg-emerald-950/30 border-emerald-300 dark:border-emerald-800'
                  : 'bg-amber-50 dark:bg-amber-950/40 border-amber-300 dark:border-amber-700/80'
              }`}
            >
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
                <div className="space-y-1">
                  <div className="flex items-center space-x-2">
                    <AlertTriangle
                      className={`w-4 h-4 shrink-0 ${
                        item.spike_excluded ? 'text-emerald-600 dark:text-emerald-400' : 'text-amber-600 dark:text-amber-400'
                      }`}
                    />
                    <span className="text-xs font-bold text-slate-900 dark:text-white flex items-center gap-1.5">
                      <span>One-Time Surge Caution</span>
                      <span className="text-[10px] font-mono font-semibold px-1.5 py-0.5 rounded bg-amber-100 dark:bg-amber-900/50 text-amber-800 dark:text-amber-300">
                        Chronic Patient ~{item.spike_analysis.spikeFactor}x Surge
                      </span>
                    </span>
                  </div>
                  <p className="text-[11px] text-slate-600 dark:text-slate-300 leading-relaxed">
                    {item.spike_analysis.cautionMessage}
                  </p>
                  <div className="text-[11px] font-mono pt-1 text-slate-700 dark:text-slate-400 flex items-center gap-3 flex-wrap">
                    <span>
                      Dumb ERP Order:{' '}
                      <del className="text-rose-600 dark:text-rose-400 font-bold">{item.spike_analysis.rawSuggestedQty} units</del>
                    </span>
                    <span>→</span>
                    <span>
                      Recommended Dampened:{' '}
                      <strong className="text-emerald-700 dark:text-emerald-400 font-bold">
                        {item.spike_analysis.dampenedSuggestedQty} units
                      </strong>
                    </span>
                    <span className="text-amber-700 dark:text-amber-400 font-bold">
                      (Saves ₹{item.spike_analysis.capitalAtRisk.toLocaleString('en-IN')} working capital)
                    </span>
                  </div>
                </div>

                <button
                  type="button"
                  onClick={() => toggleExcludeSpike(item.id)}
                  className={`px-3 py-2 rounded-lg text-xs font-bold shrink-0 transition-all cursor-pointer font-mono shadow-xs active:scale-95 ${
                    item.spike_excluded
                      ? 'bg-emerald-600 hover:bg-emerald-700 text-white'
                      : 'bg-amber-500 hover:bg-amber-600 text-slate-950 font-black'
                  }`}
                >
                  {item.spike_excluded ? '✓ Spike Excluded (Safe Mode)' : '⚡ Exclude Spike & Order Dampened'}
                </button>
              </div>
            </div>
          </div>
        )}
      </div>
    );
  };

  const uniqueDistributors = Array.from(new Set(draftItems.map((it) => it.primary_distributor.name)));

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-7 text-slate-900 dark:text-slate-100">
      {/* Top Bar Header */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4 pb-5 border-b border-slate-200 dark:border-slate-800">
        <div>
          <div className="flex items-center space-x-2">
            <span className="px-2 py-0.5 text-[10px] font-mono font-bold rounded bg-teal-50 dark:bg-teal-950/50 text-teal-800 dark:text-teal-300 border border-teal-200 dark:border-teal-800 uppercase">
              Automated Reorder Drafts
            </span>
            <span className="text-xs text-slate-500 font-mono">Dynamic POS &amp; Demand Velocity Sync</span>
          </div>
          <h2 className="text-xl sm:text-2xl font-black text-slate-900 dark:text-white mt-1 tracking-tight">
            Triage &amp; Approve Replenishment Deck
          </h2>
          <p className="text-xs text-slate-500 dark:text-slate-400 mt-1">
            <strong className="text-slate-900 dark:text-white font-mono">{draftItems.length} SKUs</strong> flagged for replenishment tonight. Review quantities below before generating purchase orders.
          </p>
        </div>

        {/* Action Toggles: Group by Distributor vs Group by Urgency */}
        <div className="flex items-center space-x-1.5 bg-slate-100 dark:bg-slate-900 border border-slate-200 dark:border-slate-800 p-1 rounded-xl self-start sm:self-auto text-xs font-mono">
          <button
            onClick={() => setGroupBy('urgency')}
            className={`px-3 py-1.5 rounded-lg font-semibold transition-all cursor-pointer ${
              groupBy === 'urgency'
                ? 'bg-white dark:bg-slate-800 text-slate-900 dark:text-white font-bold shadow-xs border border-slate-200 dark:border-slate-700'
                : 'text-slate-500 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white'
            }`}
          >
            Group by Urgency
          </button>
          <button
            onClick={() => setGroupBy('distributor')}
            className={`px-3 py-1.5 rounded-lg font-semibold transition-all cursor-pointer ${
              groupBy === 'distributor'
                ? 'bg-white dark:bg-slate-800 text-slate-900 dark:text-white font-bold shadow-xs border border-slate-200 dark:border-slate-700'
                : 'text-slate-500 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white'
            }`}
          >
            Group by Distributor
          </button>
        </div>
      </div>

      {/* 4 Executive Metric Cards */}
      <div className="grid grid-cols-2 lg:grid-cols-4 gap-4 mt-5">
        <div className="bg-white dark:bg-[#0A0A0A] border border-slate-200 dark:border-neutral-800 rounded-xl p-4 shadow-xs">
          <div className="text-[10px] uppercase font-mono text-slate-500 font-semibold tracking-wider">
            Stockout Deficit
          </div>
          <div className="text-lg sm:text-xl font-black text-rose-600 dark:text-rose-400 font-mono mt-1 tabular-nums">
            2 SKUs at Risk
          </div>
          <div className="text-[11px] text-slate-500 mt-0.5">
            Below safety buffer threshold
          </div>
        </div>

        <div className="bg-white dark:bg-[#0A0A0A] border border-slate-200 dark:border-neutral-800 rounded-xl p-4 shadow-xs">
          <div className="text-[10px] uppercase font-mono text-slate-500 font-semibold tracking-wider">
            Capital Required
          </div>
          <div className="text-lg sm:text-xl font-black text-slate-900 dark:text-white font-mono mt-1 tabular-nums">
            ₹{totalReplenishmentValue.toFixed(2)}
          </div>
          <div className="text-[11px] text-slate-500 mt-0.5">
            Total for {totalUnits} recommended units
          </div>
        </div>

        <div className="bg-white dark:bg-[#0A0A0A] border border-slate-200 dark:border-neutral-800 rounded-xl p-4 shadow-xs">
          <div className="text-[10px] uppercase font-mono text-slate-500 font-semibold tracking-wider">
            Projected Margin
          </div>
          <div className="text-lg sm:text-xl font-black text-emerald-600 dark:text-emerald-400 font-mono mt-1 tabular-nums">
            24.8% Retailer Margin
          </div>
          <div className="text-[11px] text-slate-500 mt-0.5">
            Est. +₹2,140 gross profit
          </div>
        </div>

        <div className="bg-white dark:bg-[#0A0A0A] border border-slate-200 dark:border-neutral-800 rounded-xl p-4 shadow-xs">
          <div className="text-[10px] uppercase font-mono text-slate-500 font-semibold tracking-wider">
            Fulfillment SLA
          </div>
          <div className="text-lg sm:text-xl font-black text-teal-700 dark:text-teal-400 font-mono mt-1">
            Same-Day Dispatch
          </div>
          <div className="text-[11px] text-slate-500 mt-0.5">
            Guaranteed arrival by 5:00 PM
          </div>
        </div>
      </div>

      {/* Draft Items Rendering based on active grouping */}
      <div className="mt-6 space-y-6">
        {groupBy === 'urgency' ? (
          <>
            {/* Critical Urgency Section */}
            <div>
              <div className="flex items-center space-x-2 mb-3">
                <span className="w-2 h-2 rounded-full bg-rose-500 animate-pulse" />
                <h3 className="text-xs font-bold text-slate-900 dark:text-white uppercase tracking-wider font-mono">
                  Critical Deficit (&lt; Min Safety Buffer)
                </h3>
              </div>
              <div className="space-y-4">
                {draftItems.filter((it) => it.urgency === 'CRITICAL').map(renderItemCard)}
              </div>
            </div>

            {/* Normal Routine Section */}
            <div className="pt-2">
              <div className="flex items-center space-x-2 mb-3">
                <span className="w-2 h-2 rounded-full bg-emerald-500" />
                <h3 className="text-xs font-bold text-slate-900 dark:text-white uppercase tracking-wider font-mono">
                  Routine Velocity Reorder (7-Day Average Sales)
                </h3>
              </div>
              <div className="space-y-4">
                {draftItems.filter((it) => it.urgency === 'NORMAL').map(renderItemCard)}
              </div>
            </div>
          </>
        ) : (
          /* Group by Distributor */
          uniqueDistributors.map((distName) => {
            const distItems = draftItems.filter((it) => it.primary_distributor.name === distName);
            const distSubtotal = distItems.reduce(
              (acc, it) => acc + it.suggested_qty * it.primary_distributor.ptr * (1 + it.primary_distributor.gst_pct / 100),
              0
            );

            return (
              <div key={distName} className="rounded-xl border border-slate-200 dark:border-neutral-800 bg-white dark:bg-[#0A0A0A] p-4.5 shadow-xs">
                <div className="flex items-center justify-between border-b border-slate-100 dark:border-neutral-800 pb-3 mb-4">
                  <div className="flex items-center space-x-2">
                    <Building2 className="w-4 h-4 text-teal-600 dark:text-teal-400" />
                    <h3 className="text-sm font-bold text-slate-900 dark:text-white">{distName}</h3>
                    <span className="text-xs text-slate-500 font-mono">({distItems.length} SKUs)</span>
                  </div>
                  <div className="text-xs font-mono">
                    <span className="text-slate-500 mr-2">PO Subtotal:</span>
                    <strong className="text-slate-900 dark:text-white text-sm">₹{distSubtotal.toFixed(2)}</strong>
                  </div>
                </div>
                <div className="space-y-4">
                  {distItems.map(renderItemCard)}
                </div>
              </div>
            );
          })
        )}
      </div>

      {/* Confirmation & Order Punch Action Deck */}
      <div className="mt-8 p-4 sm:p-5 rounded-xl bg-white dark:bg-[#0A0A0A] border border-slate-200 dark:border-neutral-800 flex flex-col sm:flex-row items-center justify-between gap-4 shadow-xs">
        <div>
          <div className="flex items-center space-x-2">
            <ShieldCheck className="w-4 h-4 text-teal-600 dark:text-teal-400" />
            <span className="font-bold text-slate-900 dark:text-white text-sm">Non-Autonomous Pharmacist Guardrail</span>
          </div>
          <p className="text-xs text-slate-500 dark:text-slate-400 mt-0.5">
            Auto-replenishment drafts are calculated using the 7-day velocity formula. Orders will not be dispatched without your approval.
          </p>
        </div>

        <button
          onClick={handlePunchDraft}
          disabled={punching}
          className="flex items-center space-x-2 px-5 py-2.5 rounded-lg bg-teal-600 hover:bg-teal-700 text-white font-extrabold text-xs transition-all active:scale-95 disabled:opacity-50 cursor-pointer shadow-xs font-sans"
        >
          {punching ? (
            <span>Punching POs...</span>
          ) : (
            <>
              <span>Approve &amp; Punch Replenishment POs (₹{totalReplenishmentValue.toFixed(2)})</span>
              <ArrowRight className="w-4 h-4 stroke-[2.5]" />
            </>
          )}
        </button>
      </div>

      {/* Success Notification */}
      {successOrder && (
        <div className="mt-4 p-4 rounded-xl bg-emerald-50 dark:bg-emerald-950/40 border border-emerald-200 dark:border-emerald-800 text-emerald-800 dark:text-emerald-300 text-xs flex items-center justify-between">
          <div className="flex items-center space-x-2">
            <CheckCircle2 className="w-5 h-5 text-emerald-600 dark:text-emerald-400 shrink-0" />
            <span>
              Replenishment PO <strong className="font-mono text-slate-900 dark:text-white">{successOrder}</strong> confirmed and locked on Supabase!
            </span>
          </div>
          <button
            onClick={() => setSuccessOrder(null)}
            className="text-xs text-slate-500 hover:text-slate-800 dark:hover:text-white cursor-pointer font-bold"
          >
            Dismiss
          </button>
        </div>
      )}
    </div>
  );
}
