/**
 * Marg ERP & ProfitMaker On-Premise Integration Bridge
 * 
 * Solves:
 * - Direct execution into local distributor billing software (Marg ERP 9+ and ProfitMaker).
 * - Avoids forcing distributors to log into a cloud website and re-type orders manually.
 * - Generates native Marg Inward Order format (.ORD) and ProfitMaker Order Ingestion format.
 * - Defines the Local Edge Agent (daemon) architecture for seamless background file-drop.
 */

export interface ErpOrderItem {
  skuCode: string;
  brandName: string;
  batchNumber?: string;
  quantity: number;
  freeSchemeQty?: number;
  ptr: number;
  mrp: number;
  discountPct?: number;
  gstPct: number;
}

export interface ErpOrderPayload {
  orderNumber: string;
  orderDate: string; // YYYY-MM-DD
  retailerName: string;
  retailerGstin?: string;
  retailerDrugLicense?: string;
  retailerMargCode?: string; // e.g. "CARE001" mapped in distributor's Marg ledger
  distributorName: string;
  totalAmount: number;
  items: ErpOrderItem[];
}

/**
 * Generates official Marg ERP 9+ Inward Tele-Order File (.ORD / Inward Voucher)
 * 
 * Standard Marg Inward Order Specification:
 * [HEADER]
 * ORDER_NO|ORDER_DATE|PARTY_CODE|PARTY_NAME|GSTIN|DL_NO|ORDER_TOTAL
 * [ITEMS]
 * SKU_CODE|ITEM_NAME|BATCH|QTY|FREE_QTY|RATE_PTR|MRP|DISC_PCT|GST_PCT
 */
export function generateMargOrderFile(order: ErpOrderPayload): string {
  const partyCode = order.retailerMargCode || order.retailerName.replace(/[^A-Z0-9]/gi, '').slice(0, 8).toUpperCase();
  const dateFormatted = order.orderDate.replace(/-/g, ''); // YYYYMMDD

  let content = `// MARG ERP 9+ INWARD TELE-ORDER VOUCHER\r\n`;
  content += `// Generated by M37 Dynamic Ordering Engine\r\n`;
  content += `[HEADER]\r\n`;
  content += `${order.orderNumber}|${dateFormatted}|${partyCode}|${order.retailerName}|${order.retailerGstin || ''}|${order.retailerDrugLicense || ''}|${order.totalAmount.toFixed(2)}\r\n`;
  content += `[ITEMS]\r\n`;

  for (const item of order.items) {
    const free = item.freeSchemeQty || 0;
    const disc = item.discountPct || 0;
    const batch = item.batchNumber || '';
    content += `${item.skuCode}|${item.brandName}|${batch}|${item.quantity}|${free}|${item.ptr.toFixed(2)}|${item.mrp.toFixed(2)}|${disc.toFixed(2)}|${item.gstPct.toFixed(2)}\r\n`;
  }

  content += `[END_ORDER]\r\n`;
  return content;
}

/**
 * Generates ProfitMaker (Lucky Soft) Standard Wholesale Inward Order CSV
 * 
 * Standard ProfitMaker Specification:
 * H,OrderNo,OrderDate,RetailerCode,RetailerName,GrossAmount
 * D,OrderNo,ItemCode,ItemName,Batch,OrderQty,FreeQty,Rate,MRP,TaxCode
 */
export function generateProfitMakerOrderFile(order: ErpOrderPayload): string {
  const partyCode = order.retailerMargCode || order.retailerName.replace(/[^A-Z0-9]/gi, '').slice(0, 8).toUpperCase();

  const lines: string[] = [];
  // Header row
  lines.push(`H,"${order.orderNumber}","${order.orderDate}","${partyCode}","${order.retailerName}",${order.totalAmount.toFixed(2)}`);

  // Detail rows
  for (const item of order.items) {
    const free = item.freeSchemeQty || 0;
    const batch = item.batchNumber || '';
    lines.push(
      `D,"${order.orderNumber}","${item.skuCode}","${item.brandName}","${batch}",${item.quantity},${free},${item.ptr.toFixed(2)},${item.mrp.toFixed(2)},${item.gstPct}%`
    );
  }

  return lines.join('\r\n');
}

